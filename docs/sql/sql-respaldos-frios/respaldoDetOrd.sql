--  DDL for Trigger TRG_ACTUALIZARVALORESEMPLEADOS
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "USUARIO02"."TRG_ACTUALIZARVALORESEMPLEADOS" 
AFTER INSERT OR UPDATE OR DELETE
ON DETALLE_ORDENES
FOR EACH ROW
DECLARE
    v_EmpleadoID ORDENES.EMPLEADOS_EMPLEADOID%TYPE;
    v_CantidadOrdenes NUMBER;
    v_ValorOrdenes NUMBER;
BEGIN
    -- Obtener el empleado relacionado a la orden afectada
    IF INSERTING OR UPDATING THEN
        SELECT EMPLEADOS_EMPLEADOID
        INTO v_EmpleadoID
        FROM ORDENES
        WHERE ORDENID = :NEW.ORDENES_ORDENID;
    ELSIF DELETING THEN
        SELECT EMPLEADOS_EMPLEADOID
        INTO v_EmpleadoID
        FROM ORDENES
        WHERE ORDENID = :OLD.ORDENES_ORDENID;
    END IF;

    -- Calcular los totales actualizados para ese empleado
    SELECT 
        COUNT(DISTINCT O.ORDENID),
        NVL(SUM(DO.CANTIDAD * P.PRECIOUNIT),0)
    INTO 
        v_CantidadOrdenes,
        v_ValorOrdenes
    FROM ORDENES O
    JOIN DETALLE_ORDENES DO ON O.ORDENID = DO.ORDENES_ORDENID
    JOIN PRODUCTOS P ON DO.PRODUCTOS_PRODUCTOID = P.PRODUCTOID
    WHERE O.EMPLEADOS_EMPLEADOID = v_EmpleadoID;

    -- Actualizar los valores en la tabla EMPLEADOS
    UPDATE EMPLEADOS
    SET 
        CantidadOrdenes = v_CantidadOrdenes,
        ValorOrdenes = v_ValorOrdenes
    WHERE EMPLEADOID = v_EmpleadoID;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
END;

/
ALTER TRIGGER "USUARIO02"."TRG_ACTUALIZARVALORESEMPLEADOS" ENABLE;
