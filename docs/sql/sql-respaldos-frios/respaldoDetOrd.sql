--  DDL for Trigger TRG_ACTUALIZA_EXISTENCIA
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "USUARIO02"."TRG_ACTUALIZA_EXISTENCIA" 
AFTER INSERT OR UPDATE OR DELETE
ON DETALLE_ORDENES
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        UPDATE PRODUCTOS
        SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD
        WHERE PRODUCTOID = :NEW.PRODUCTOID;

    ELSIF UPDATING THEN
        UPDATE PRODUCTOS
        SET EXISTENCIA = EXISTENCIA + (:OLD.CANTIDAD - :NEW.CANTIDAD)
        WHERE PRODUCTOID = :OLD.PRODUCTOID;

    ELSIF DELETING THEN
        UPDATE PRODUCTOS
        SET EXISTENCIA = EXISTENCIA + :OLD.CANTIDAD
        WHERE PRODUCTOID = :OLD.PRODUCTOID;
    END IF;
END;

/
ALTER TRIGGER "USUARIO02"."TRG_ACTUALIZA_EXISTENCIA" ENABLE;
